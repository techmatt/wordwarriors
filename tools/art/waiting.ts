/**
 * The words waiting for art (item 191): `content/art/waiting.ts`, derived from
 * `public/art/`, never written by hand. A bank word waits while its `pic_<word>`
 * is missing, still carries the placeholder mark (`art:placeholders`), or is
 * byte for byte the same file as another word's picture (hunt 13's shared
 * stand-in). The bank stores a waiting word (`WAITING_WHY`), so it is in no pool
 * until `art:pick` promotes a picture of its own.
 *
 * `art:placeholders`, `art:gen` and `art:pick` rewrite the file after their art
 * changes; `npx tsx tools/art/waiting.ts` rewrites it by hand. A change rewrites
 * the golden draws and the recorder's `?missing` too (they follow the live words). A unit test
 * (tests/unit/waiting.test.ts) fails when it disagrees with the PNGs.
 */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { BANK } from '../../content/phonics/bank.js';
import { ART_DIR, exists, runMain } from '../shared.js';

export const WAITING_FILE = path.join('content', 'art', 'waiting.ts');

const MARK = Buffer.from('tEXtWordWarriors\0placeholder', 'latin1');

/** The bank words with no picture of their own, sorted, from the PNGs on disk. */
export async function waitingWords(dir = ART_DIR): Promise<string[]> {
  const waiting = new Set<string>();
  const byHash = new Map<string, string[]>();
  for (const w of BANK.map((b) => b.word)) {
    const f = path.join(dir, `pic_${w}.png`);
    if (!(await exists(f))) {
      waiting.add(w);
      continue;
    }
    const png = await readFile(f);
    if (png.includes(MARK)) waiting.add(w);
    const h = createHash('md5').update(png).digest('hex');
    byHash.set(h, [...(byHash.get(h) ?? []), w]);
  }
  for (const ws of byHash.values()) if (ws.length > 1) for (const w of ws) waiting.add(w);
  return [...waiting].sort();
}

export function waitingSource(words: readonly string[]): string {
  return [
    '// Generated by tools/art/waiting.ts (`art:placeholders`, `art:gen` and `art:pick` rewrite it). Do not hand-edit.',
    '// The bank words whose `pic_<word>` is missing, still the painted placeholder, or one stand-in shared',
    '// with another word: each is stored until its own picture is promoted (content/phonics/bank.ts).',
    `export const WAITING_FOR_ART: readonly string[] = [${words.map((w) => `'${w}'`).join(', ')}];`,
    '',
  ].join('\n');
}

/** Run a tsx script in a fresh process: this one's bank was loaded before the art changed. */
function runTsx(file: string, ...args: string[]): void {
  execFileSync(process.execPath, ['--import', 'tsx', file, ...args], { stdio: 'inherit' });
}

/**
 * Rewrite content/art/waiting.ts from the PNGs. When it changed, a word went live
 * (or out), so the files derived from the live words follow: the golden seeded
 * draws (tests/unit/plansGolden.json), the phonics recorder's `?missing` and
 * docs/art.md's order.
 */
export async function writeWaiting(opts: { follow?: boolean } = {}): Promise<{ changed: boolean; words: string[] }> {
  const words = await waitingWords();
  const src = waitingSource(words);
  const before = (await exists(WAITING_FILE)) ? await readFile(WAITING_FILE, 'utf8') : '';
  const changed = before !== src;
  if (changed) await writeFile(WAITING_FILE, src);
  console.log(`art: ${WAITING_FILE}: ${words.length ? `waiting for art: ${words.join(', ')}` : 'no word waiting for art'}${changed ? ' (rewritten)' : ''}`);
  if (changed || opts.follow) {
    // Each runs even if one before it failed; a failure is reported once all have run, and
    // `npx tsx tools/art/waiting.ts --follow` reruns them (the list no longer changes by then).
    const failed: string[] = [];
    const follow = (what: string, file: string, ...args: string[]) => {
      try {
        runTsx(file, ...args);
        console.log(`art: ${what} rewritten (the live words changed)`);
      } catch {
        failed.push(what);
      }
    };
    follow('tests/unit/plansGolden.json', path.join('tests', 'unit', 'plansGolden.ts'));
    follow("the recorder's ?missing", path.join('tools', 'recorder', 'missing.ts'));
    // docs/art.md lists the word pictures live words first, so its order follows too.
    follow('docs/art.md', path.join('tools', 'art', 'placeholders.ts'), '--doc-only');
    if (failed.length) throw new Error(`${failed.join(', ')} not rewritten: fix, then run \`npx tsx tools/art/waiting.ts --follow\``);
  }
  return { changed, words };
}

runMain(import.meta.url, async () => void (await writeWaiting({ follow: process.argv.includes('--follow') })), 'art:waiting failed: ');
